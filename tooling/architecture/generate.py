#!/usr/bin/env python3
"""Deterministic Flutter import graph and source-symbol inventory (stdlib only)."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = "docs/architecture/CODE-MAP.md"
DART_CLASS = re.compile(r"^\s*(?:abstract\s+)?class\s+([A-Za-z_]\w*)\b")
DART_FUNCTION = re.compile(
    r"^\s*(?:static\s+)?(?:Future(?:<[^>]+>)?|void|Widget|String|bool|int|double"
    r"|Stream(?:<[^>]+>)?)\s+(?:(?:get)\s+)?([A-Za-z_]\w*)\s*(?:\(|=>|\{)"
)
IMPORT = re.compile(r"^\s*import\s+'([^']+)';")


def inventory(root: Path) -> str:
    base = root / "mobile/lib"
    paths = sorted(base.rglob("*.dart"))
    names = {path.relative_to(root).as_posix(): i for i, path in enumerate(paths)}
    symbols = {}
    links = set()
    for path in paths:
        rel = path.relative_to(root).as_posix()
        found = []
        for line in path.read_text(encoding="utf-8").splitlines():
            a, b = DART_CLASS.search(line), DART_FUNCTION.search(line)
            if a:
                found.append("class " + a.group(1))
            if b:
                found.append("fn " + b.group(1) + "()")
            imp = IMPORT.search(line)
            if imp and not imp.group(1).startswith(("package:", "dart:")):
                target = (path.parent / imp.group(1)).resolve()
                try:
                    ref = target.relative_to(root.resolve()).as_posix()
                except ValueError:
                    continue
                if ref in names:
                    links.add((rel, ref))
        symbols[rel] = list(dict.fromkeys(found))
    fence = chr(96) * 3
    out = [
        "# Flutter code map",
        "",
        "> Generated from checked-in Dart files. Do not edit this file manually.",
        "> To refresh: python3 tooling/architecture/generate.py --write",
        "> CI runs the same command with --check to detect drift.",
        "",
        "## Actual Dart imports",
        "",
        fence + "mermaid",
        "flowchart LR",
    ]
    for rel, i in names.items():
        out.append(f'    N{i}["{rel}"]')
    for a, b in sorted(links):
        out.append(f"    N{names[a]} --> N{names[b]}")
    out += [fence, "", "## Declared classes and functions", ""]
    for rel in names:
        out.append("### " + rel)
        out.append("")
        for symbol in symbols[rel]:
            out.append("- " + symbol)
        if not symbols[rel]:
            out.append("- No classes or named methods matched by the simple inventory parser")
        out.append("")
    out += [
        "## Limitations",
        "",
        "This is a lexical source inventory, not a compiler AST or runtime call graph.",
        "It does not discover anonymous callbacks, reflection, dependency injection,",
        "Firebase rules or dynamic dispatch. Use SYSTEM.md for architectural intent",
        "and use Flutter analysis and tests for behavior.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="Regenerate CODE-MAP.md")
    parser.add_argument("--check", action="store_true", help="Fail when CODE-MAP.md is stale")
    args = parser.parse_args()
    generated = inventory(ROOT)
    target = ROOT / DEST
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generated, encoding="utf-8")
        print("Updated " + DEST)
        return 0
    if not target.exists() or target.read_text(encoding="utf-8") != generated:
        print("ERROR: Flutter code map is stale. Run python3 tooling/architecture/generate.py --write")
        return 1
    print("Flutter code map is current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
