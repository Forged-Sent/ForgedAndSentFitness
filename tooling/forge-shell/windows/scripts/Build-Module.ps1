#requires -Version 7.5
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference='Stop'
$moduleDir=Join-Path (Split-Path -Parent $PSScriptRoot) 'modules\Forge'
$source=[IO.File]::ReadAllText((Join-Path $moduleDir 'Forge.psm1'))
$coreMarker=". (Join-Path `$PSScriptRoot 'Core.ps1')"
$loop=@'
foreach ($part in @('Prompt','Editing','Catalog','Navigation','Productivity','Engineering','Project')) {
    . (Join-Path $PSScriptRoot "$part.ps1")
}
'@
if(-not $source.Contains($coreMarker) -or -not $source.Contains($loop)){throw 'Module source layout changed; update the build markers before installing.'}
$source=$source.Replace($coreMarker,([IO.File]::ReadAllText((Join-Path $moduleDir 'Core.ps1'))))
$parts=foreach($name in @('Prompt','Editing','Catalog','Navigation','Productivity','Engineering','Project')){"# Source: $name.ps1`n"+[IO.File]::ReadAllText((Join-Path $moduleDir "$name.ps1"))}
$source="# Generated by scripts/Build-Module.ps1. Edit the modular sources, then run reloadforge.`n"+$source.Replace($loop,($parts -join "`n"))
$tokens=$null;$errors=$null;$null=[Management.Automation.Language.Parser]::ParseInput($source,[ref]$tokens,[ref]$errors)
if($errors.Count){throw 'Generated runtime has syntax errors; original retained.'}
$target=Join-Path $moduleDir 'Forge.Runtime.psm1'
$old=if([IO.File]::Exists($target)){[IO.File]::ReadAllText($target)}else{''}
if($Check){if($old -cne $source){throw 'Runtime cache is stale. Run scripts/Build-Module.ps1 or reloadforge.'};return}
if($old -cne $source){$tmp=$target+'.tmp';[IO.File]::WriteAllText($tmp,$source,[Text.UTF8Encoding]::new($false));[IO.File]::Move($tmp,$target,$true)}
